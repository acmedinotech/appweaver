/**
 * Provides automated data normalization against user-supplied data from a `@Model` definition:
 * 
 * - user.data is prepared against modelDef:
 *   - process each key-value:
 *     - if mode=='create': # override user
 *       - if isAutoGenerated, use autoCreatedValue() or undefined
 *     - if mode=='update': # override user
 *       - if isReadOnly: remove key
 *       - else if isAutoUpdated: set with autoUpdatedValue() or remove key
 *   - inject system key-value overrides
 * - hydrate prepared data
 * - validate prepared data
 */
export const prepareDataForMutation = (modelDef: ModelDefinition, mode: 'create' | 'update', data: any, options?: { injectData?: Record<string, any>; removeKeys?: string[] }) => {
    const result: ReturnType<ModelDefinition['prepareData']> = {
        data: {},
        removed: {},
    }

    const { injectData = {}, removeKeys = [] } = (options ?? {});
    const isCreate = mode === 'create';
    const isUpdate = !isCreate;

    for (const [propertyKey, meta] of Object.entries(modelDef.properties)) {
        const isReadOnly = meta.isReadOnly || meta.isAutoCreated || meta.isAutoUpdated;
        if (meta.isAutoCreated) {
            // case: always remove; only auto-add back on-create
            result.removed[propertyKey] = data[propertyKey];
            if (isCreate && meta.autoCreatedValue) {
                result.data[propertyKey] = meta.autoCreatedValue(propertyKey, modelDef);
            }
        } else if (meta.isAutoUpdated) {
            // case: always remove; only auto-add back on-update
            result.removed[propertyKey] = data[propertyKey];
            if (isUpdate && meta.autoUpdatedValue) {
                result.data[propertyKey] = meta.autoUpdatedValue(propertyKey, modelDef);
            }
        } else if (isUpdate && isReadOnly) {
            // case: always remove on-update
            result.removed[propertyKey] = data[propertyKey];
        } else {
            result.data[propertyKey] = data[propertyKey];
        }
    }

    // inject system key-value overrides
    result.data = { ...result.data, ...injectData };
    for (const key of removeKeys) {
        if (result.data[key] === undefined) continue;
        result.removed[key] = result.data[key];
        delete result.data[key];
    }

    return result;
}

